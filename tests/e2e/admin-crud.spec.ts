import { randomUUID } from "node:crypto";
import { hash } from "bcryptjs";
import type { PrismaClient } from "@prisma/client";
import { createDatabaseClient } from "../../src/lib/db/client";
import { expect, test } from "@playwright/test";
import { cookieConsentStorageKey } from "../../src/features/cookie-consent/consent";
const databaseUrl = process.env.E2E_DATABASE_URL;
test.skip(!databaseUrl, "Requires isolated local PostgreSQL.");
let db: PrismaClient, userId: string;
const marker = randomUUID(), email = `crud-${marker}@example.test`, password = randomUUID(), slug = `audit-ui-${marker}`;
test.beforeAll(async () => {
  if (!databaseUrl) return;
  const url = new URL(databaseUrl);
  if (!["localhost", "127.0.0.1"].includes(url.hostname) || !/^belin_product_e2e_[a-z0-9_]+$/.test(url.pathname.slice(1))) throw new Error("Unsafe database");
  db = createDatabaseClient(databaseUrl);
  userId = (await db.user.create({ data: { email, role: "ADMIN", passwordHash: await hash(password, 12) } })).id;
});
test.afterAll(async () => { if (!db) return; await db.product.deleteMany({ where: { slug } }); await db.auditLog.deleteMany({ where: { actorId: userId } }); await db.user.delete({ where: { id: userId } }); await db.$disconnect(); });
test("admin creates, edits and deletes a product without losing variant input focus or fetching every image list", async ({ page }) => {
  await page.addInitScript(key => localStorage.setItem(key, JSON.stringify({ necessary: true, analytics: false, marketing: false })), cookieConsentStorageKey);
  await page.goto("/login");
  await page.getByLabel("E-mail", { exact: true }).fill(email); await page.getByLabel("Senha", { exact: true }).fill(password);
  let redundantImageRequests = 0;
  page.on("request", request => { if (request.method() === "GET" && /\/api\/admin\/products\/[^/]+\/images$/.test(new URL(request.url()).pathname)) redundantImageRequests++; });
  await page.getByRole("button", { name: "Entrar", exact: true }).click();
  await expect(page).toHaveURL(/\/admin$/, { timeout: 15000 });
  const form = page.locator("form").filter({ has: page.getByRole("heading", { name: /^(Novo produto|Editar produto)$/ }) });
  const originalName = `CRUD ${marker}`;
  await form.getByLabel("Nome", { exact: true }).fill(originalName); await form.getByLabel("Slug", { exact: true }).fill(slug);
  await form.getByRole("button", { name: "Adicionar tamanho/cor", exact: true }).click();
  const size = form.getByLabel("Tamanho", { exact: true }); const color = form.getByLabel("Cor", { exact: true });
  await size.pressSequentially("GG"); await expect(size).toBeFocused(); await expect(size).toHaveValue("GG");
  await color.pressSequentially("Bordô"); await expect(color).toBeFocused(); await expect(color).toHaveValue("Bordô");
  await form.getByRole("button", { name: "Criar produto", exact: true }).click();
  const card = page.getByRole("listitem").filter({ has: page.getByRole("heading", { name: originalName, exact: true }) });
  await expect(card).toBeVisible({ timeout: 15000 });
  await card.getByRole("button", { name: "Editar", exact: true }).click();
  const changed = `Editada ${marker}`;
  await form.getByLabel("Nome", { exact: true }).fill(changed);
  await form.getByRole("button", { name: "Salvar alterações", exact: true }).click();
  const edited = page.getByRole("listitem").filter({ has: page.getByRole("heading", { name: changed, exact: true }) });
  await expect(edited).toBeVisible();
  expect((await db.product.findUniqueOrThrow({ where: { slug }, include: { variants: true } })).variants[0]).toMatchObject({ size: "GG", color: "Bordô" });
  page.once("dialog", dialog => dialog.accept());
  await edited.getByRole("button", { name: "Excluir", exact: true }).click();
  await expect(edited).toHaveCount(0);
  expect(await db.product.findUnique({ where: { slug } })).toBeNull();
  expect(redundantImageRequests).toBe(0);
});
